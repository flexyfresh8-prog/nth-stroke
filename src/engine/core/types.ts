/**
 * NTH Stroke — Autonomous Drawing Engine
 * Core shared types. The engine core is framework-agnostic and runs both in
 * a Web Worker (browser) and in Node (tests/verification) without DOM APIs.
 */

export interface Vec2 {
  x: number;
  y: number;
}

/** Artistic stages of the workflow (spec §4, A–G). */
export type Stage =
  | 'observation'
  | 'construction'
  | 'refinement'
  | 'tonal'
  | 'shading'
  | 'detail'
  | 'correction'
  | 'complete';

export const STAGE_ORDER: Stage[] = [
  'observation', 'construction', 'refinement', 'tonal', 'shading', 'detail', 'correction', 'complete',
];

/** Physical instruments (spec §6). Monochrome studio. */
export type InstrumentId =
  | 'pencil-2h'
  | 'pencil-hb'
  | 'pencil-2b'
  | 'pencil-4b'
  | 'pencil-6b'
  | 'mechanical'
  | 'charcoal'
  | 'stump'
  | 'eraser-kneaded'
  | 'eraser-precision';

export const INSTRUMENT_IDS: InstrumentId[] = [
  'pencil-2h', 'pencil-hb', 'pencil-2b', 'pencil-4b', 'pencil-6b',
  'mechanical', 'charcoal', 'stump', 'eraser-kneaded', 'eraser-precision',
];

export type InstrumentClass = 'pencil' | 'charcoal' | 'blender' | 'eraser';

/** One timed sample from the virtual stylus — the atomic motor event. */
export interface StylusSample {
  /** Simulated time (ms) since engine start. */
  t: number;
  /** Tip position in canvas pixels. */
  x: number;
  y: number;
  /** Height of the tip above the paper (px, 0 = contact). */
  z: number;
  /** Normalized force 0..1 — evolves continuously. */
  pressure: number;
  /** Speed (px/ms). */
  v: number;
  /** Tilt away from the vertical (radians). */
  tilt: number;
  /** Azimuth of the tilt (radians). */
  azimuth: number;
}

/** What the planner asks the hand to do. */
export interface DrawOp {
  id: number;
  kind: 'stroke' | 'utility';
  stage: Stage;
  instrument: InstrumentId;
  /** Human readable objective, surfaced in the UI. */
  intent: string;
  /** Planner waypoints in canvas pixels (>= 2). */
  waypoints: Vec2[];
  /** Intended steady pressure 0..1. */
  pressure: number;
  /** Pace multiplier (1 = natural). */
  speed: number;
  /** Scene region this op belongs to (-1 = global). */
  region: number;
  /** True when generated by the correction planner. */
  corrective: boolean;
  /** Recorded reason for corrective ops (spec §8). */
  reason?: string;
  /** Pen-up travel is performed before the op by the motor controller. */
  travel: boolean;
  /** Broad side-of-tip strokes (tonal blocking, charcoal work) — wider flat
   *  contact and stronger tilt, like a pencil laid on its side. */
  broad?: boolean;
}

/** Result of executing a DrawOp — the actual stylus trajectory. */
export interface OpTrace {
  opId: number;
  /** All samples in simulated-time order, pen-up travel included. */
  samples: StylusSample[];
  /** Samples while the pen is down (contact), in order. */
  contact: StylusSample[];
  /** Total simulated duration of the op including travel (ms). */
  durationMs: number;
  /** Distance travelled pen-up before drawing (px). */
  travelPx: number;
  /** Distance drawn pen-down (px). */
  drawPx: number;
  /** Mean / peak pressure actually applied. */
  meanPressure: number;
  peakPressure: number;
}

/** Live engine snapshot streamed to the UI. */
export interface EngineSnapshot {
  stage: Stage;
  objective: string;
  instrument: InstrumentId | null;
  opCount: number;
  simTimeMs: number;
  wallTimeMs: number;
  cursor: { x: number; y: number; z: number };
  pressure: number;
  phase: 'idle' | 'travel' | 'draw' | 'utility' | 'thinking';
  running: boolean;
  done: boolean;
  metrics: LiveMetrics;
  progress: number;
}

export interface LiveMetrics {
  /** Multiscale SSIM estimate (0..1). */
  ssim: number;
  /** Mean absolute tone error vs reference (0..1). */
  toneError: number;
  /** Fraction of important reference edges covered by drawn strokes (0..1). */
  edgeAlignment: number;
  /** Mean local contrast error (0..1). */
  contrastError: number;
  /** Structural error of drawn contour placement vs scene structure (0..1). */
  structureError: number;
}

export interface EngineConfig {
  /** Deterministic seed — same seed + same inputs => same drawing. */
  seed: number;
  /** Approximate op budget (engine stops around this if metrics plateau). */
  opBudget: number;
  /** 0..1 — how much detail work relative to blocking. */
  detailLevel: number;
  /** 0..1 — target fidelity; 0 = loose artistic, 1 = tight rendering. */
  fidelity: number;
  /** Paper tooth strength 0..1. */
  paperGrain: number;
  /** Let the engine manage instruments (default) — otherwise bias to this one. */
  preferredInstrument: InstrumentId | 'auto';
  /** Whether semantic models may be used when available. */
  useModels: boolean;
}

